// Hearth-<env>-Data (C11-D27): what the services keep between releases, pulled forward from C0.12 by
// the owner's answer to C11-Q01 (C11-D35), so the api can start and realtime's /ready/local can pass
// before C0.12's data plane: a single-node Valkey and the generated AUTH_SECRET, and the two SSM
// parameters the Services stack reads them by. It stands on the Platform stack's isolated subnets
// and Valkey security group, read by name (C11-D24), and the stage turns its termination protection
// on.
//
// Valkey: one cache.t4g.micro node, cluster mode disabled (the server uses one ioredis client), no
// failover or Multi-AZ, transit encryption required and encryption at rest, port 6379, maxmemory-policy
// noeviction (T19 item 16), and no password until C0.12's ACL users. Snapshot retention 0, no
// persistence and no slow-log delivery, which meets TECH-SPEC T23 item 6's settings, so Valkey needs no
// entry in the retention registry. A node replacement empties it: sign-in attempts and windows start
// again, and the realtime streams' epoch makes their readers refetch. The version is TECH-SPEC T9's
// line, the one the local and CI stack runs, so CI and AWS run one major version (design C11-D35 said
// the newest 8.x); the set-up runbook reads back the versions and families ElastiCache offers in
// ap-southeast-1 before this stack first deploys, and a difference is a reviewed change here first
// (TECH-SPEC T24 item 14).
//
// The AUTH_SECRET: generated by CloudFormation (64 letters and digits), so its value is never in a
// template; the AWS-managed key; no rotation, which with AUTH_SECRET_PREVIOUS is C0.12's. Only the
// api's execution role may read it (roles.ts). Its full ARN crosses to the Services stack by SSM,
// since a by-name import of a name ending in a hyphen and six characters (`-secret`) gives a partial
// ARN that Secrets Manager misreads as a suffix.
//
// Kept on delete or update: non-prod's and prod's replication groups, and every stage's secret. The
// restore stage (C11-D45) has its replication group only while restoreActive is set, with
// CloudFormation's default delete, so the next deploy without it removes it rather than leaving a
// billed node behind; between drills its endpoint parameter holds a placeholder host, so the Services
// stack renders the same shape at desired 0. Its secret always exists (a deleted secret's name stays
// taken for its recovery window, which would refuse the next drill's create), and is its own: whether
// a real restore needs prod's is C0.17's. The subnet and parameter groups always exist; they cost
// nothing. C0.12 still owns the ACL users, the memory alarm, a customer-managed key, any replica, and
// the AUTH_SECRET's rotation.
import * as cdk from 'aws-cdk-lib'
import * as elasticache from 'aws-cdk-lib/aws-elasticache'
import * as secretsmanager from 'aws-cdk-lib/aws-secretsmanager'
import * as ssm from 'aws-cdk-lib/aws-ssm'
import { Construct } from 'constructs'
import { authSecretName, SSM_PARAMETER, valkeyGroupId } from '../config/names.ts'
import type { EnvironmentName, Profile } from '../config/profiles.ts'
import type { WorkloadRun } from './stage.ts'

// TECH-SPEC T9's line, the local and CI stack's; read back against what ElastiCache offers before
// the first deploy (TECH-SPEC T24 item 14).
export const VALKEY_VERSION = '9.1'
export const VALKEY_FAMILY = 'valkey9'
export const VALKEY_NODE = 'cache.t4g.micro'
// The restore stage's Valkey host between drills (C11-D45): RFC 2606's reserved .invalid.
export const PENDING_VALKEY_HOST = 'valkey.pending.invalid'
const VALKEY_PORT = 6379

export interface DataStackProps extends cdk.StackProps {
  environment: EnvironmentName
  profile: Profile
  run: WorkloadRun
}

export class DataStack extends cdk.Stack {
  constructor(scope: Construct, id: string, props: DataStackProps) {
    super(scope, id, props)
    const { environment, profile, run } = props
    // Whether the replication group exists: always where the services run, and in the restore stage
    // only while it is active.
    const active = profile.live === true || run.restoreActive

    const valkey = new Construct(this, 'Valkey')
    const subnets = new elasticache.CfnSubnetGroup(valkey, 'Subnets', {
      description: `Hearth ${environment} Valkey, in the isolated subnets (C11-D35)`,
      subnetIds: ssm.StringListParameter.valueForTypedListParameter(this, SSM_PARAMETER.isolatedSubnets(environment)),
    })
    const settings = new elasticache.CfnParameterGroup(valkey, 'Settings', {
      cacheParameterGroupFamily: VALKEY_FAMILY,
      description: `Hearth ${environment} Valkey, which evicts nothing (C11-D35)`,
      properties: { 'maxmemory-policy': 'noeviction' },
    })
    let endpoint = PENDING_VALKEY_HOST
    if (active) {
      const group = new elasticache.CfnReplicationGroup(valkey, 'Group', {
        replicationGroupId: valkeyGroupId(environment),
        replicationGroupDescription: `Hearth ${environment} Valkey (C11-D35)`,
        engine: 'valkey',
        engineVersion: VALKEY_VERSION,
        cacheNodeType: VALKEY_NODE,
        numCacheClusters: 1,
        automaticFailoverEnabled: false,
        multiAzEnabled: false,
        transitEncryptionEnabled: true,
        transitEncryptionMode: 'required',
        atRestEncryptionEnabled: true,
        snapshotRetentionLimit: 0,
        port: VALKEY_PORT,
        cacheParameterGroupName: settings.ref,
        cacheSubnetGroupName: subnets.ref,
        securityGroupIds: [
          ssm.StringParameter.valueForStringParameter(this, SSM_PARAMETER.securityGroup(environment, 'valkey')),
        ],
      })
      // The restore stage's takes CloudFormation's default delete, so a deploy without it removes it.
      if (profile.live === true) group.applyRemovalPolicy(cdk.RemovalPolicy.RETAIN_ON_UPDATE_OR_DELETE)
      endpoint = group.attrPrimaryEndPointAddress
    }

    const secret = new secretsmanager.Secret(this, 'AuthSecret', {
      secretName: authSecretName(environment),
      description: `Hearth ${environment} AUTH_SECRET, which every sign-in key derives from (C11-D35)`,
      generateSecretString: { passwordLength: 64, excludePunctuation: true },
      removalPolicy: cdk.RemovalPolicy.RETAIN_ON_UPDATE_OR_DELETE,
    })

    // What the Services stack reads by name (C11-D24).
    const parameters = new Construct(this, 'Parameters')
    new ssm.StringParameter(parameters, 'ValkeyEndpoint', {
      parameterName: SSM_PARAMETER.valkeyEndpoint(environment),
      stringValue: endpoint,
    })
    new ssm.StringParameter(parameters, 'AuthSecretArn', {
      parameterName: SSM_PARAMETER.authSecretArn(environment),
      stringValue: secret.secretArn,
    })
  }
}
